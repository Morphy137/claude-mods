// Turns the catalog in characters.js into the mod's sprite data.
// Run from the repository root: node preview/build-avatars.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const OUTPUT = join(here, '..', 'agent-dashboard', 'hooks', 'avatar-data.ts')
const W = 12
const H = 14
const KEY_POOL = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789'
// Catalog category id -> the mod's role id.
const ROLE_OF = {
  ORC: 'orchestrator', ARC: 'architect', INS: 'inspector', GUA: 'guard', TES: 'chemist',
  DEB: 'detective', RES: 'scholar', WRI: 'scribe', DES: 'designer', REL: 'pilot',
  IDX: 'miner', PRO: 'chef', EXP: 'scout', BUI: 'builder', SPE: 'wizard',
}

const source = readFileSync(join(here, 'characters.js'), 'utf8')
const { ANIME_CATEGORIES, ANIMATIONS } = new Function(`${source}\nreturn { ANIME_CATEGORIES, ANIMATIONS }`)()

function paint(name, parts) {
  const grid = Array.from({ length: H }, () => Array(W).fill(null))
  for (const { rows, colors } of parts) {
    for (const [y, pattern] of Object.entries(rows)) {
      if (pattern.length !== W) throw new Error(`${name} row ${y}: "${pattern}"`)
      ;[...pattern].forEach((ch, x) => {
        if (ch === '.') return
        if (!colors[ch]) throw new Error(`${name}: no color for "${ch}"`)
        grid[y][x] = colors[ch]
      })
    }
  }
  const keyOf = new Map()
  const layer = grid.map(row => row.map(hex => {
    if (!hex) return '.'
    if (!keyOf.has(hex)) keyOf.set(hex, KEY_POOL[keyOf.size])
    return keyOf.get(hex)
  }).join(''))
  return { layer, palette: Object.fromEntries([...keyOf].map(([hex, key]) => [key, hex])) }
}

function sprite(character) {
  const extra = ANIMATIONS[character.name] ?? {}
  const parts = character.parts
    .map((p, i) => (extra.animate?.[i] ? { ...p, anim: extra.animate[i] } : p))
    .concat(extra.fx ?? [])
  return {
    name: character.name,
    ...paint(character.name, parts.filter(p => !p.anim)),
    animated: parts.filter(p => p.anim).map(p => ({ ...paint(character.name, [p]), anim: p.anim, fxOnly: Boolean(p.fxOnly) })),
    motion: extra.motion ?? 'bob',
    ...(character.body ? { body: character.body } : {}),
    ...(character.eyes ? { eyes: character.eyes } : {}),
  }
}

const data = Object.fromEntries(ANIME_CATEGORIES.map(category => {
  const role = ROLE_OF[category.id]
  if (!role) throw new Error(`no role for category ${category.id}`)
  return [role, category.characters.map(sprite)]
}))

const header = `// Generated by preview/build-avatars.mjs from preview/characters.js; edit those, then rerun it.

export type SpriteMotion = 'bob' | 'float' | 'shake' | 'fade' | 'jiggle'

/** Pixel rows ('.' is empty, any other letter a palette color) on the critter's 12x14 grid. */
export type SpriteLayer = { layer: string[]; palette: Record<string, string> }

export type Sprite = SpriteLayer & {
  name: string
  /** Parts that move while busy; fxOnly ones are drawn only then. */
  animated: Array<SpriteLayer & { anim: string; fxOnly: boolean }>
  motion: SpriteMotion
  /** Critter recolor; absent keeps the default body. */
  body?: string
  /** Eye recolor, only where black eyes would vanish on the body. */
  eyes?: string
}

`
writeFileSync(OUTPUT, `${header}export const SPRITES: Record<string, Sprite[]> = ${JSON.stringify(data, null, 1)}\n`)
console.log(`wrote ${Object.values(data).flat().length} sprites to ${OUTPUT}`)
